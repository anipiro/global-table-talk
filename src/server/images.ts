import { generateImage, IMAGE, LANG_NAME, MODELS, type db } from "@/lib/ai.server";

/** AI illustrations: generated through the gateway, uploaded to the private `photos` bucket under generated/,
 *  stored in `media` with a long-lived signed URL. Never people or faces, never text in the image. */

type Supa = ReturnType<typeof db>;
type AskJson = <T>(request: Request, model: string, system: string, user: string) => Promise<T | null>;

const SIGNED_URL_SECONDS = 60 * 60 * 24 * 30; // 30 days: outlives the night and the demo
export const NO_PEOPLE = "No people, no human figures, no faces, no hands. No text, letters, logos or watermarks anywhere in the image.";
export const TONIGHT = "tonight"; // media.query of the recap hero image

/** Uploads generated bytes and returns a signed URL. Falls back to the room's own folder if generated/ is refused. */
export async function storeGenerated(supa: Supa, roomId: string, img: { bytes: Uint8Array; contentType: string }) {
  const ext = img.contentType.split("/")[1]?.replace("jpeg", "jpg") ?? "png";
  const id = crypto.randomUUID();
  const opts = { contentType: img.contentType, upsert: false };
  let path = `generated/${roomId}/${id}.${ext}`;
  let up = await supa.storage.from("photos").upload(path, img.bytes, opts);
  if (up.error) {
    console.warn("generated/ upload refused, using room folder", up.error.message);
    path = `${roomId}/generated-${id}.${ext}`;
    up = await supa.storage.from("photos").upload(path, img.bytes, opts);
    if (up.error) throw new Error(`Upload failed: ${up.error.message}`);
  }
  const { data, error } = await supa.storage.from("photos").createSignedUrl(path, SIGNED_URL_SECONDS);
  if (error || !data) throw new Error(`Couldn't sign the image URL: ${error?.message ?? "unknown"}`);
  return data.signedUrl;
}

export type PaintResult = "added" | "reused";

const hasTonight = async (supa: Supa, roomId: string) => {
  const { data } = await supa.from("media").select("id").eq("room_id", roomId).eq("kind", "reference_image").eq("query", TONIGHT).limit(1);
  return !!data?.length;
};

/** "Tonight, painted": one high-quality illustration of the evening per room, the recap screen's hero image. */
export async function paintTonight(request: Request, supa: Supa, askJson: AskJson, roomId: string): Promise<PaintResult> {
  if (await hasTonight(supa, roomId)) return "reused";

  // The night's things: notebook topics (never person entries), pictures found, meme ideas.
  const [{ data: notes }, { data: media }, { data: members }] = await Promise.all([
    supa.from("notebook").select("kind, title, body").eq("room_id", roomId).neq("kind", "person"),
    supa.from("media").select("kind, query").eq("room_id", roomId),
    supa.from("members").select("language").eq("room_id", roomId),
  ]);
  const things = [
    ...(notes ?? []).map((n) => `${n.kind}: ${n.title} — ${n.body}`),
    ...(media ?? []).filter((m) => m.query !== TONIGHT).map((m) => `${m.kind === "meme" ? "joke" : "picture"}: ${m.query}`),
  ];
  const langs = [...new Set((members ?? []).map((m) => m.language))];

  const plan = await askJson<{ scene?: string; captions?: Record<string, string> }>(request, MODELS.trigger,
    `Turn the things from a dinner party into ONE scene for a warm painterly illustration of the evening.
Use places, foods, drinks, objects and the mood; turn jokes into small playful objects or details. Leave out every person and name.
JSON: {"scene": "max 60 words, English, objects and setting only", "captions": {${langs.map((l) => `"${l}": "max 6 words in ${LANG_NAME[l]}, like 'Tonight, painted'"`).join(", ")}}}`,
    things.length ? things.join("\n") : "(a quiet evening: no topics recorded)");
  const scene = String(plan?.scene ?? "").trim() || "A long Georgian supra table at night with khachapuri, wine in clay jugs and candles.";

  const img = await generateImage(request,
    `Warm painterly illustration, rich golden evening light, cosy and celebratory. ${scene} ${NO_PEOPLE}`, IMAGE.painted);
  if (await hasTonight(supa, roomId)) return "reused"; // a second recap press finished first
  const url = await storeGenerated(supa, roomId, img);

  const caption_by_language: Record<string, string> = { en: "Tonight, painted" };
  for (const l of langs) if (plan?.captions?.[l]) caption_by_language[l] = String(plan.captions[l]).trim();
  await supa.from("media").insert({
    room_id: roomId, kind: "reference_image", query: TONIGHT, url, caption_by_language, credit: "AI illustration",
  });
  return "added";
}
